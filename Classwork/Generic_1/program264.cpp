#include<iostream>
using namespace std;

int Maximum(int No1, int No2)
{
    if(No1 > No2)
    {
        return No1;
    }
    else
    {
        return No2;
    }
}

////////////////////////////////////////////////////////////////////////
//
//  Entry point function : Main
//
////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue1 = 10, iValue2 = 11, iRet = 0;

    iRet = Maximum(iValue1, iValue2);
    cout <<"Maximum : " <<iRet<< "\n";      // 11

    return 0;
}