#include<iostream>
using namespace std;

double Maximum(double No1, double No2)
{
    if(No1 > No2)
    {
        return No1;
    }
    else
    {
        return No2;
    }
}

////////////////////////////////////////////////////////////////////////
//
//  Entry point function : Main
//
////////////////////////////////////////////////////////////////////////

int main()
{
    double dValue1 = 10.0, dValue2 = 11.0, dRet = 0.0;

    dRet = Maximum(dValue1, dValue2);
    cout <<"Maximum : " <<dRet<< "\n";      // 11

    return 0;
}